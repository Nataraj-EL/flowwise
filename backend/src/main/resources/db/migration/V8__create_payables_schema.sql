-- Sprint 15: Payables Intelligence Schema Migration

CREATE TABLE payables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id BIGINT NOT NULL,
    vendor VARCHAR(255) NOT NULL,
    bill_reference VARCHAR(100) NOT NULL UNIQUE,
    bill_amount NUMERIC(15, 2) NOT NULL,
    amount_paid NUMERIC(15, 2) NOT NULL DEFAULT 0.00,
    outstanding_amount NUMERIC(15, 2) NOT NULL,
    bill_date TIMESTAMP WITH TIME ZONE NOT NULL,
    due_date TIMESTAMP WITH TIME ZONE NOT NULL,
    category VARCHAR(50) NOT NULL, -- INVENTORY, RENT, UTILITIES, LOGISTICS, SOFTWARE, TAX
    status VARCHAR(50) NOT NULL, -- DUE_TODAY, DUE_7_DAYS, DUE_30_DAYS, OVERDUE, PAID
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payables_merchant FOREIGN KEY (merchant_id) REFERENCES merchants (id) ON DELETE CASCADE
);

CREATE INDEX idx_payables_merchant_id ON payables(merchant_id);
CREATE INDEX idx_payables_status ON payables(status);

